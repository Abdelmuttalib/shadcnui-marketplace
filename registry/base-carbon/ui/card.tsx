import * as React from "react";
import { cn } from "cn";

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card bg-cb-card text-cb-card-foreground ring-cb-foreground/10 rounded-cb-xl *:[img:last-child]:rounded-b-cb-xl *:[img:first-child]:rounded-t-cb-xl flex flex-col gap-(--card-spacing) overflow-hidden py-(--card-spacing) text-sm shadow-xs ring-1 [--card-spacing:--spacing(6)] has-[>img:first-child]:pt-0 data-[size=sm]:[--card-spacing:--spacing(4)]",
        className
      )}
      {...props}
    />
  );
}

